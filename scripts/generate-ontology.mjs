import fs from 'node:fs';

const ontology = JSON.parse(fs.readFileSync(new URL('../backend/ontology.json', import.meta.url)));
const phrases = JSON.parse(fs.readFileSync(new URL('../shared/non-dairy.json', import.meta.url)));
const output = '// Generated by scripts/generate-ontology.mjs; edit backend/ontology.json and shared/non-dairy.json.\n'
  + `export const ONTOLOGY = ${JSON.stringify(ontology)};\n`
  + `export const NON_DAIRY_PHRASES = ${JSON.stringify(phrases)};\n`;
const destination = new URL('../src/ontology.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Run node scripts/generate-ontology.mjs');
} else {
  fs.writeFileSync(destination, output);
}
